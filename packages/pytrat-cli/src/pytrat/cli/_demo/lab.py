"""Development key material and configuration for the demo.

Everything is generated fresh at run time: no key material is committed. Private keys are written
with mode 0600, exactly as the reference TTS requires.

Two ways to get a :class:`Lab`:

* :meth:`Lab.create` generates every key into one directory (``demo.py``, ``serve.py``).
* :meth:`Lab.load` reads keys that were generated elsewhere (the Docker Compose deployment): each
  container holds only its own private keys, plus the public JWKS files and demo CA certificate.
"""

from __future__ import annotations

import json
import os
import ssl
import time
import uuid
from collections.abc import Mapping
from dataclasses import dataclass, field
from pathlib import Path

from pytrat.core import SecretToken, StaticKeySet, VerificationKey, WorkloadKeys
from pytrat.core.crypto import (
    PrivateKey,
    generate_private_key,
    load_private_key_pem,
    private_key_to_pem,
    sign_compact,
)

TRUST_DOMAIN = "payments.internal"
TTS_ISSUER = "https://tts.payments.internal"
IDP_ISSUER = "https://idp.example"
API_AUDIENCE = "https://api.payments.example"
SCOPE = "payments.transfer"
TRANSFER_FIELDS = ("source_account", "destination_account", "amount_minor", "currency")
ALG = "ES256"
KEY_NAMES = ("tts", "idp", "api-gateway", "payment-service")


@dataclass(frozen=True, slots=True)
class Urls:
    """Where each service is reachable."""

    tts: str = "https://tts.payments.internal"
    gateway: str = "https://gateway.payments.internal"
    payment: str = "https://payment.payments.internal"
    ledger: str = "https://ledger.payments.internal"

    @property
    def token_endpoint(self) -> str:
        """The TTS token endpoint."""
        return f"{self.tts}/token"

    @property
    def insecure_localhost(self) -> bool:
        """True when running the services over plain HTTP on loopback (local multi-process mode)."""
        return self.tts.startswith("http://127.0.0.1")


@dataclass(frozen=True, slots=True)
class Lab:
    """Keys and configuration shared by the four services.

    Attributes:
        directory: Writable working directory (TTS configuration side files, audit database).
        urls: Where each service is reachable.
        keys: The private keys this process holds, by name (a subset of :data:`KEY_NAMES`).
        public_keys: Public keys of every named key, by name.
        key_directory: Where the private key files of :attr:`keys` live.
        ca_bundle: CA certificate that outbound HTTPS clients trust. ``None`` means the default
            system trust store (the in-process and loopback demos never use TLS).
    """

    directory: Path
    urls: Urls
    keys: Mapping[str, PrivateKey] = field(repr=False)
    public_keys: Mapping[str, VerificationKey]
    key_directory: Path
    ca_bundle: Path | None = None

    @classmethod
    def create(cls, directory: Path, urls: Urls | None = None) -> Lab:
        """Generate keys (TTS, identity provider, gateway, payment service) into ``directory``."""
        directory.mkdir(parents=True, exist_ok=True)
        keys = {name: generate_private_key(ALG) for name in KEY_NAMES}
        for name, key in keys.items():
            write_private(directory / f"{name}.pem", private_key_to_pem(key))
        return cls(
            directory=directory,
            urls=urls or Urls(),
            keys=keys,
            public_keys={name: verification_key(name, key) for name, key in keys.items()},
            key_directory=directory,
        )

    @classmethod
    def load(
        cls,
        *,
        directory: Path,
        key_directory: Path,
        public_directory: Path,
        urls: Urls,
        ca_bundle: Path,
    ) -> Lab:
        """Load keys generated by another process (see ``payment_demo.pki``).

        Every ``<name>.pem`` present in ``key_directory`` becomes a held private key; every
        public key is read from ``<public_directory>/<name>.jwks.json``.

        Raises:
            FileNotFoundError: If a public JWKS file or the CA bundle is missing.
            ConfigurationError: If a JWKS document is invalid.
        """
        if not ca_bundle.is_file():
            raise FileNotFoundError(f"CA bundle not found: {ca_bundle}")
        keys = {
            name: load_private_key_pem(path.read_bytes())
            for name in KEY_NAMES
            if (path := key_directory / f"{name}.pem").is_file()
        }
        public_keys: dict[str, VerificationKey] = {}
        for name in KEY_NAMES:
            key_set = StaticKeySet.from_jwks_file(public_directory / f"{name}.jwks.json")
            trusted = key_set.get(name)
            if trusted is None or len(key_set) != 1:
                raise FileNotFoundError(f"{name}.jwks.json must hold exactly the key {name!r}")
            public_keys[name] = trusted
        directory.mkdir(parents=True, exist_ok=True)
        return cls(
            directory=directory,
            urls=urls,
            keys=keys,
            public_keys=public_keys,
            key_directory=key_directory,
            ca_bundle=ca_bundle,
        )

    def pem(self, name: str) -> Path:
        """Path of a private key this process holds."""
        return self.key_directory / f"{name}.pem"

    def tls_verify(self) -> ssl.SSLContext | bool:
        """What outbound HTTPS clients verify servers against.

        With a CA bundle, a context that trusts *only* the demo CA (no system roots) and checks
        host names; otherwise ``True``, httpx's default verification.
        """
        if self.ca_bundle is None:
            return True
        return ssl.create_default_context(cafile=self.ca_bundle)

    def public_jwks(self, *names: str) -> dict[str, object]:
        """Public JWKS for the named keys; the kid is the key's name."""
        return StaticKeySet(self.public_keys[name] for name in names).to_jwks()

    def tts_keys(self) -> StaticKeySet:
        """The TTS verification keys every resource service trusts."""
        return StaticKeySet.from_jwks(self.public_jwks("tts"))

    def workload_keys(self) -> WorkloadKeys:
        """Keys resource services trust for workload authentication, by owning workload.

        A workload JWT authenticates only the workload that owns the verifying key.
        """
        return WorkloadKeys(
            {
                name: StaticKeySet.from_jwks(self.public_jwks(name))
                for name in ("api-gateway", "payment-service")
            }
        )

    def user_access_token(self, subject: str = "user:123") -> SecretToken:
        """An access token the identity provider issued after the user logged in."""
        now = int(time.time())
        claims = {
            "iss": IDP_ISSUER,
            "aud": API_AUDIENCE,
            "sub": subject,
            "scope": SCOPE,
            "iat": now,
            "exp": now + 600,
            "client_id": "web-app",
            "jti": uuid.uuid4().hex,
        }
        raw = sign_compact(claims, self.keys["idp"], alg=ALG, kid="idp", typ="at+jwt")
        return SecretToken(raw)

    def tts_settings(self) -> dict[str, object]:
        """Configuration document for the reference TTS (see packages/pytrat-server/examples)."""
        (self.directory / "idp.jwks.json").write_text(json.dumps(self.public_jwks("idp")))
        return {
            "trust_domain": TRUST_DOMAIN,
            "issuer": TTS_ISSUER,
            "token_endpoint": self.urls.token_endpoint,
            "token_lifetime_seconds": 60,
            "algorithms": [ALG],
            "audit_db_path": "tts-audit.sqlite3",
            "signing_keys": [
                {
                    "kid": "tts",
                    "alg": ALG,
                    "private_key_path": str(self.pem("tts").resolve()),
                    "state": "active",
                }
            ],
            "workloads": [
                {"id": "api-gateway", "jwks": self.public_jwks("api-gateway")},
                {"id": "payment-service", "jwks": self.public_jwks("payment-service")},
            ],
            "subject_tokens": {
                "jwt_access_token": [
                    {"issuer": IDP_ISSUER, "jwks_path": "idp.jwks.json", "audience": API_AUDIENCE}
                ]
            },
            "issuance_policy": {
                "workloads": {
                    "api-gateway": {
                        "scopes": [SCOPE],
                        "tctx": {
                            "source_account": "string",
                            "destination_account": "string",
                            "amount_minor": "integer",
                            "currency": "string",
                        },
                        "rctx": {"channel": "string"},
                    }
                }
            },
        }


def verification_key(name: str, private_key: PrivateKey) -> VerificationKey:
    """The public half of a generated key; the kid is the key's name."""
    return VerificationKey.from_public_key(name, private_key.public_key(), ALG)


def write_private(path: Path, data: bytes) -> None:
    """Write secret material readable only by the owner (mode 0600), replacing any old file."""
    descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    os.fchmod(descriptor, 0o600)  # O_CREAT's mode does not apply to a file that already exists
    with os.fdopen(descriptor, "wb") as handle:
        handle.write(data)
